"""Data models for the SUPERVISOR AI coding supervision system."""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional


class LifecycleState(str, Enum):
    """Lifecycle states of the supervision and repair process."""

    IMPLEMENTING = "IMPLEMENTING"
    REVIEW_PENDING = "REVIEW_PENDING"
    REVIEWING = "REVIEWING"
    FIXES_REQUIRED = "FIXES_REQUIRED"
    REPAIRING = "REPAIRING"
    VERIFYING = "VERIFYING"
    PASSED = "PASSED"
    BLOCKED = "BLOCKED"
    RETRY_LIMIT_REACHED = "RETRY_LIMIT_REACHED"


class Severity(str, Enum):
    """Severity levels for review findings."""

    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


class Category(str, Enum):
    """Categories of review findings according to Stage 4 requirements."""

    BUG = "BUG"
    MISSING_REQUIREMENT = "MISSING_REQUIREMENT"
    REGRESSION = "REGRESSION"
    SECURITY = "SECURITY"
    ERROR_HANDLING = "ERROR_HANDLING"
    DEPENDENCY_CONFIG = "DEPENDENCY_CONFIG"
    INTEGRATION = "INTEGRATION"
    TESTING = "TESTING"
    PERFORMANCE = "PERFORMANCE"
    SPEC_MISMATCH = "SPEC_MISMATCH"


class Confidence(str, Enum):
    """Confidence level of a finding, separating confirmed defects from heuristic warnings."""

    CONFIRMED = "CONFIRMED"
    HEURISTIC = "HEURISTIC"


class FindingStatus(str, Enum):
    """Status of an individual finding."""

    CONFIRMED = "CONFIRMED"
    SUSPECTED = "SUSPECTED"
    RECOMMENDED = "RECOMMENDED"
    RESOLVED = "RESOLVED"
    UNRESOLVED = "UNRESOLVED"
    WONT_FIX = "WONT_FIX"


class TestStatus(str, Enum):
    """Execution status of test suites, distinguishing runs from missing infrastructure."""

    PASSED = "PASSED"
    FAILED = "FAILED"
    NOT_RUN = "NOT_RUN"
    NOT_AVAILABLE = "NOT_AVAILABLE"
    BLOCKED = "BLOCKED"
    PARTIAL = "PARTIAL"


class ReviewStatus(str, Enum):
    """High-level outcome status of a supervisor review run."""

    PASSED = "PASSED"
    FIXES_REQUIRED = "FIXES_REQUIRED"
    VERIFICATION_INCOMPLETE = "VERIFICATION_INCOMPLETE"
    BLOCKED = "BLOCKED"


@dataclass
class Finding:
    """A structured finding generated by SUPERVISOR.
    
    Supports both legacy attribute access and Prompt 4 fields.
    """

    finding_id: str
    severity: Severity
    category: Category
    file_path: str
    description: str
    evidence: str
    why_it_matters: str
    recommended_correction: str
    verification_method: str
    line_number: Optional[int] = None
    title: str = ""
    confidence: Confidence = Confidence.CONFIRMED
    status: FindingStatus = FindingStatus.CONFIRMED
    source_check: str = "core_engine"
    cycle: int = 1

    def __post_init__(self):
        if not self.title:
            self.title = self.description[:80]

    # Property aliases for backward compatibility and specification compliance
    @property
    def id(self) -> str:
        return self.finding_id

    @property
    def file(self) -> str:
        return self.file_path

    @property
    def line(self) -> Optional[int]:
        return self.line_number

    @property
    def recommended_action(self) -> str:
        return self.recommended_correction

    @property
    def verification_status(self) -> str:
        return self.status.value

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["id"] = self.finding_id
        data["file"] = self.file_path
        data["line"] = self.line_number
        data["severity"] = self.severity.value
        data["category"] = self.category.value
        data["confidence"] = self.confidence.value
        data["status"] = self.status.value
        data["recommended_action"] = self.recommended_correction
        data["verification_status"] = self.status.value
        return data

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> Finding:
        fid = d.get("finding_id") or d.get("id") or "FINDING-UNKNOWN"
        fpath = d.get("file_path") or d.get("file") or ""
        lineno = d.get("line_number") if "line_number" in d else d.get("line")
        rec = d.get("recommended_correction") or d.get("recommended_action") or ""
        status_raw = d.get("status") or d.get("verification_status") or FindingStatus.CONFIRMED.value
        conf_raw = d.get("confidence", Confidence.CONFIRMED.value)

        return cls(
            finding_id=fid,
            severity=Severity(d["severity"]),
            category=Category(d["category"]),
            file_path=fpath,
            line_number=lineno,
            description=d.get("description", ""),
            evidence=d.get("evidence", ""),
            why_it_matters=d.get("why_it_matters", ""),
            recommended_correction=rec,
            verification_method=d.get("verification_method", ""),
            title=d.get("title", ""),
            confidence=Confidence(conf_raw) if conf_raw in Confidence.__members__ else Confidence.CONFIRMED,
            status=FindingStatus(status_raw) if status_raw in FindingStatus.__members__ else FindingStatus.CONFIRMED,
            source_check=d.get("source_check", "core_engine"),
            cycle=d.get("cycle", 1),
        )


@dataclass
class TaskSpec:
    """The task description, preserved from Stage 1 through Stage 9."""

    task_id: str
    prompt: str
    title: str = ""
    requirements: List[str] = field(default_factory=list)
    context_files: List[str] = field(default_factory=list)
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> TaskSpec:
        return cls(
            task_id=d["task_id"],
            prompt=d["prompt"],
            title=d.get("title", ""),
            requirements=d.get("requirements", []),
            context_files=d.get("context_files", []),
            created_at=d.get("created_at", datetime.now(timezone.utc).isoformat()),
        )


@dataclass
class TestResult:
    """Record of an actual test or validation command execution."""

    command: str
    exit_code: int
    stdout: str
    stderr: str
    duration_seconds: float
    passed: bool
    status: TestStatus = TestStatus.NOT_RUN
    reason: Optional[str] = None

    def __post_init__(self):
        if self.status == TestStatus.NOT_RUN:
            if self.exit_code == 0:
                self.status = TestStatus.PASSED
            elif self.exit_code == -1:
                self.status = TestStatus.BLOCKED
            else:
                self.status = TestStatus.FAILED

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["status"] = self.status.value
        return data

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> TestResult:
        st_raw = d.get("status")
        status = TestStatus(st_raw) if st_raw in TestStatus.__members__ else TestStatus.NOT_RUN
        return cls(
            command=d["command"],
            exit_code=d["exit_code"],
            stdout=d.get("stdout", ""),
            stderr=d.get("stderr", ""),
            duration_seconds=d.get("duration_seconds", 0.0),
            passed=d.get("passed", d.get("exit_code") == 0),
            status=status,
            reason=d.get("reason"),
        )


@dataclass
class CheckRecord:
    """Record of an individual check executed or skipped by the engine."""

    check_name: str
    target: str
    status: str  # "EXECUTED", "SKIPPED", "FAILED"
    reason: Optional[str] = None
    duration_seconds: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> CheckRecord:
        return cls(
            check_name=d["check_name"],
            target=d["target"],
            status=d["status"],
            reason=d.get("reason"),
            duration_seconds=d.get("duration_seconds", 0.0),
        )


@dataclass
class SupervisorReport:
    """Structured report produced at Stage 5 and Stage 7."""

    report_id: str
    task_id: str
    cycle: int
    state: LifecycleState
    findings: List[Finding] = field(default_factory=list)
    tests_run: List[TestResult] = field(default_factory=list)
    changed_files: List[str] = field(default_factory=list)
    summary: str = ""
    blocker_reason: Optional[str] = None
    checks_executed: List[CheckRecord] = field(default_factory=list)
    checks_skipped: List[CheckRecord] = field(default_factory=list)
    limitations: List[str] = field(default_factory=list)
    overall_status: ReviewStatus = ReviewStatus.PASSED
    workspace_fingerprint: str = ""
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    def __post_init__(self):
        if self.has_material_issues:
            self.overall_status = ReviewStatus.FIXES_REQUIRED
        elif self.blocker_reason:
            self.overall_status = ReviewStatus.BLOCKED
        elif any(t.status == TestStatus.NOT_AVAILABLE for t in self.tests_run):
            self.overall_status = ReviewStatus.VERIFICATION_INCOMPLETE
        else:
            self.overall_status = ReviewStatus.PASSED

    @property
    def material_findings(self) -> List[Finding]:
        """Findings that require correction (Critical, High, Medium, confirmed/unresolved)."""
        blocking_severities = {Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM}
        return [
            f
            for f in self.findings
            if f.severity in blocking_severities
            and f.status in {FindingStatus.CONFIRMED, FindingStatus.UNRESOLVED}
        ]

    @property
    def has_material_issues(self) -> bool:
        return len(self.material_findings) > 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "report_id": self.report_id,
            "task_id": self.task_id,
            "cycle": self.cycle,
            "state": self.state.value,
            "overall_status": self.overall_status.value,
            "findings": [f.to_dict() for f in self.findings],
            "tests_run": [t.to_dict() for t in self.tests_run],
            "checks_executed": [c.to_dict() for c in self.checks_executed],
            "checks_skipped": [c.to_dict() for c in self.checks_skipped],
            "limitations": self.limitations,
            "workspace_fingerprint": self.workspace_fingerprint,
            "changed_files": self.changed_files,
            "summary": self.summary,
            "blocker_reason": self.blocker_reason,
            "created_at": self.created_at,
        }

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> SupervisorReport:
        ostatus = d.get("overall_status")
        overall = ReviewStatus(ostatus) if ostatus in ReviewStatus.__members__ else ReviewStatus.PASSED
        return cls(
            report_id=d["report_id"],
            task_id=d["task_id"],
            cycle=d["cycle"],
            state=LifecycleState(d["state"]),
            findings=[Finding.from_dict(f) for f in d.get("findings", [])],
            tests_run=[TestResult.from_dict(t) for t in d.get("tests_run", [])],
            checks_executed=[CheckRecord.from_dict(c) for c in d.get("checks_executed", [])],
            checks_skipped=[CheckRecord.from_dict(c) for c in d.get("checks_skipped", [])],
            limitations=d.get("limitations", []),
            overall_status=overall,
            workspace_fingerprint=d.get("workspace_fingerprint", ""),
            changed_files=d.get("changed_files", []),
            summary=d.get("summary", ""),
            blocker_reason=d.get("blocker_reason"),
            created_at=d.get("created_at", datetime.now(timezone.utc).isoformat()),
        )
